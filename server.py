# Spelling-fix patches: id -> RGBA PIL image (the feathered word patch).
# Generated by /api/fix/generate, re-registered from their embedded PNGs when
# a draft reopens or an export body carries them — so a restarted server can
# always resolve every fix a client still references.
PATCHES: dict = {}


def _patch_image(pid: str):
    return PATCHES.get(pid)


imaging.set_patch_resolver(_patch_image)


def _register_fix(fx: dict) -> None:
    """Cache a fix dict's embedded base64 PNG under its id (idempotent)."""
    pid = str(fx.get("id", "") or "")
    if not pid or pid in PATCHES or not fx.get("png"):
        return
    try:
        import base64
        raw = base64.b64decode(fx["png"])
        PATCHES[pid] = Image.open(io.BytesIO(raw)).convert("RGBA")
    except Exception:
        pass


def _register_fixes_from_pages(pages: list) -> None:
    """Walk page-settings dicts (and their overlays) and cache every patch."""
    for ps in pages or []:
        if not isinstance(ps, dict):
            continue
        for fx in ps.get("fixes") or []:
            if isinstance(fx, dict):
                _register_fix(fx)
        for ov in ps.get("overlays") or []:
            if isinstance(ov, dict):
                for fx in ov.get("fixes") or []:
                    if isinstance(fx, dict):
                        _register_fix(fx)

