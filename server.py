# ---------------------------------------------------------------------------
# Export filenames
#
# Bordered exports are named "<BOARD>_<MEDIUM>_<SUBJECT>_CH<nn>-ChapterName.pdf"
# — e.g. MP_EN_PHY_CH01-ElectricCharges.pdf. The board code is derived from the
# cover's board name ("MP Board" -> MP); the medium (EN/HN) and subject
# (PHY/CHEM/BIO/…) codes come straight from the Borders tab.
# ---------------------------------------------------------------------------

_WORDS = re.compile(r"[^A-Za-z0-9]+")


def _code(value: str, limit: int = 12) -> str:
    """Squash a label into a filename-safe upper-case code."""
    return _WORDS.sub("", str(value or "")).upper()[:limit]


def _board_code(board: str) -> str:
    """'MP Board' -> 'MP'; 'UP' -> 'UP'."""
    words = [w for w in _WORDS.split(str(board or "")) if w]
    named = [w for w in words if w.lower() not in ("board", "boards")]
    return _code((named or words or [""])[0], 6)


def _camel(text: str) -> str:
    """'Electric charges' -> 'ElectricCharges' (chapter name in filenames)."""
    joined = "".join(w[:1].upper() + w[1:]
                     for w in _WORDS.split(str(text or "")) if w)
    return joined[:80]              # keep the whole name well inside 255 chars


def _chapter_tag(number: str, name: str) -> str:
    """'5', 'Electric charges' -> 'CH05-ElectricCharges'."""
    num = str(number or "").strip()
    parts = []
    if num:
        parts.append("CH" + (num.zfill(2) if num.isdigit() else _code(num, 6)))
    nm = _camel(name)
    if nm:
        parts.append(nm)
    return "-".join(parts)


def _coded_name(board: str, medium: str, subject: str, number: str, name: str,
                ext: str = ".pdf") -> str | None:
    """Coded filename, or None when no board/medium/subject code was picked."""
    codes = [c for c in (_board_code(board), _code(medium, 4),
                         _code(subject, 6)) if c]
    if not codes:
        return None
    tag = _chapter_tag(number, name)
    return "_".join(codes + ([tag] if tag else [])) + ext


def _export_name(orig_name: str, bordered: bool, number: str, name: str,
                 board: str = "", medium: str = "", subject: str = "") -> str:
    """
    Coded chapter filename (MP_EN_PHY_CH01-Name.pdf) once the Borders tab
    carries at least one of board/medium/subject; a readable
    "Chapter 05 - Name.pdf" when it only carries chapter info; else *_fixed.
    """
    stem = os.path.splitext(orig_name)[0]
    if bordered:
        coded = _coded_name(board, medium, subject, number, name)
        if coded:
            return coded
    if bordered and (number.strip() or name.strip()):
        parts = []
        if number.strip():
            parts.append(f"Chapter {number.strip()}")
        if name.strip():
            parts.append(name.strip())
        base = " - ".join(parts)
        base = re.sub(r'[\\/:*?"<>|]+', "", base)
        base = re.sub(r"\s+", " ", base).strip()
        if base:
            return base + ".pdf"
    return stem + "_fixed.pdf"


def _send_board_zip(pages: list, covers: list, bcfg: dict, dpi: int,
                    orig_name: str, number: str, name: str,
                    medium: str, subject: str):
    """
    "All boards": one PDF per board — identical notes, that board's cover as
    page 1 — delivered as a single zip. The pages are rendered once and shared
    across every PDF; only the cover differs.
    """
    used: set = set()
    tmpdir = tempfile.mkdtemp(dir=WORK_DIR, prefix="zip_")
    buf = io.BytesIO()
    try:
        # PDF pages are already JPEG-compressed inside the PDF, so deflating
        # them again only burns CPU — store them as they are.
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as zf:
            for i, (board, cover) in enumerate(covers):
                member = _export_name(orig_name, True, number, name,
                                      board, medium, subject)
                if member in used:          # two boards sharing a code
                    member = f"{os.path.splitext(member)[0]}_{i + 1}.pdf"
                used.add(member)
                imgs = [borders.load_cover(cover, bcfg["template_size"])
                        .convert("RGB")] + pages
                path = os.path.join(tmpdir, f"{i:02d}.pdf")
                imgs[0].save(path, "PDF", resolution=float(dpi),
                             save_all=True, append_images=imgs[1:])
                zf.write(path, arcname=member)
                os.remove(path)             # keep only one PDF on disk at a time
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)
    buf.seek(0)
    zname = (_coded_name("ALL", medium, subject, number, name, ".zip")
             or os.path.splitext(orig_name)[0] + "_all_boards.zip")
    return send_file(buf, mimetype="application/zip",
                     as_attachment=True, download_name=zname)


@app.route("/api/export", methods=["POST"])
def export():
    """
    Body: {
      job, dpi?, settings: { fid: { pages: [ {angle, rotate, persp, crop, removals} ] } },
      borders?: { on, class, board, stream, number, name, medium, subject }
    }
    Every loaded file's pages go into the SAME document, in rail order, so an
    export is one PDF — except with borders' board set to "__all__", where the
    same document is written once per board (each with its own cover page) and
    the set comes back as a zip.
    """
    data = request.get_json(force=True)
    job_id = data.get("job", "")
    dpi = int(data.get("dpi") or DEFAULT_EXPORT_DPI)
    settings = data.get("settings", {})
    watermark = bool(data.get("watermark", False))
    # Global switch stamps every page; a page whose settings carry a "wmo"
    # override ({on, opacity, scale, rotate, dx, dy}) uses that instead —
    # its own on/off and its own parameters. Legacy clients sent wmScope
    # 'page' + per-page "wm" flags; still honoured below.
    wm_scope = str(data.get("wmScope", "all") or "all")
    wm_opacity = float(data.get("wmOpacity", 1) or 1)
    wm_scale = float(data.get("wmScale", 1) or 1)
    wm_rotate = float(data.get("wmRotate", 0) or 0)
    wm_dx = float(data.get("wmDx", 0) or 0)
    wm_dy = float(data.get("wmDy", 0) or 0)
    wm_center_margins = bool(data.get("wmCenterMargins", False))
    job = _job(job_id)
    palette = job.get("palette")

    # Cache every spelling-fix patch the client sent (each fix embeds its
    # PNG), so the render loop below can resolve them even after a restart.
    for fset0 in settings.values():
        if isinstance(fset0, dict):
            _register_fixes_from_pages(fset0.get("pages") or [])

    # Borders (branded frames + chapter header + optional board/stream cover).
    bd = data.get("borders") or {}
    bd_on = bool(bd.get("on"))
    bcfg = bcover = brenderer = None
    btpls: list = []
    bcovers: list = []          # "All boards": one (board, cover) per output PDF
    bnumber = str(bd.get("number", "") or "")
    bname = str(bd.get("name", "") or "")
    bboard = str(bd.get("board", "") or "")
    bstream = str(bd.get("stream", "") or "")
    bmedium = str(bd.get("medium", "") or "")
    bsubject = str(bd.get("subject", "") or "")
    ball = bool(bd.get("allBoards")) or bboard == ALL_BOARDS
    bzoom = borders._clampf(bd.get("zoom", 1))
    bstretch_w = borders._clampf(bd.get("stretchW", 1))
    bstretch_h = borders._clampf(bd.get("stretchH", 1))
    bfit_mode = str(bd.get("fitMode") or "") \
        or ("width" if bd.get("fitWidth") else "page")
    if bfit_mode not in ("page", "width", "fill"):
        bfit_mode = "page"
    if bd_on:
        bcls = str(bd.get("class", "") or "")
        try:
            bcfg = borders.load_config(bcls)
        except LookupError as e:
            return jsonify({"error": str(e)}), 400
        btpls = borders.list_templates(bcls)
        if not btpls:
            return jsonify({"error": f"no border templates for class {bcls} "
                            f"yet — add PNGs to borders/{bcls}/templates/"}), 400
        if ball:
            # One PDF per board that has a cover for the picked stream
            # (streamless classes match their board-only covers).
            bcovers = borders.boards_with_covers(bcls, bstream)
            if not bcovers:
                return jsonify({"error": f"no {bcls} cover pages for "
                                + (f"stream {bstream}" if bstream
                                   else "the boards — pick a stream")}), 400
        elif bboard:
            # Streamless classes (10th) store covers under the board alone;
            # a board picked without a stream where streams DO exist simply
            # exports without a cover, as before.
            bcover = borders.find_cover(bcls, bboard, bstream)
            if bcover is None and bstream:
                return jsonify({"error": f"no cover page for {bboard} / {bstream}"}), 400
        brenderer = borders.HeaderRenderer(bcfg, bnumber, bname, bmedium)

    # Every loaded PDF exports into ONE document, in rail order — an export is
    # always a single PDF, never a zip of separate ones.
    out_images = []

    # Merged-page overlays reference source pages by fid+page; they may live in
    # any loaded PDF, so keep one lazily-opened doc per fid for the whole export.
    fid_paths = {f["fid"]: f["path"] for f in job["files"]}
    src_docs: dict = {}

    def _render_overlay_src(ov):
        fid = str(ov.get("fid", "") or "")
        path = fid_paths.get(fid)
        if path is None:
            return None
        d = src_docs.get(fid)
        if d is None:
            d = src_docs[fid] = fitz.open(path)
        pno = int(ov.get("page", 0) or 0)
        if not 0 <= pno < d.page_count:
            return None
        return imaging.render_page(d, pno, dpi)

    # One headless browser serves the chapter header (no-op when off). The
    # frame never changes size, so a single overlay serves every page.
    with (brenderer if brenderer is not None else contextlib.nullcontext()):
        bheader = brenderer.render(bcfg["template_size"][0], 1.0, 1.0) \
            if bd_on else None
        for f in job["files"]:
            fset = settings.get(f["fid"], {})
            page_settings = fset.get("pages", [])
            doc = fitz.open(f["path"])
            images = []
            tpl_i = 0                       # frame designs cycle per file
            # Pages render in the order the editor sends them (reordering);
            # each entry's "src" is the page's index inside the working PDF.
            if page_settings:
                ordered = [(int(ps.get("src", idx)), ps)
                           for idx, ps in enumerate(page_settings)]
            else:
                ordered = [(i, {}) for i in range(doc.page_count)]
            for i, ps in ordered:
                if not 0 <= i < doc.page_count:
                    continue
                if ps.get("deleted"):
                    continue          # page was deleted in the editor — skip it
                angle = float(ps.get("angle", f["pages"][i]["angle"]))
                rot = float(ps.get("rotate", 0) or 0)
                persp = ps.get("persp")
                crop = ps.get("crop", f["pages"][i]["crop"])
                removals = ps.get("removals") if "removals" in ps else f["pages"][i].get("removals")
                color = ps.get("color") or imaging.DEFAULT_COLOR
                # Content pulled from other pages is part of the page too: where
                # it sits past the margins the sheet grows to keep it instead of
                # clipping it. Everything downstream measures against that grown
                # box — only the watermark still anchors to the real margins.
                ecrop = imaging.expanded_crop(crop, ps.get("overlays"))
                hi = imaging.render_page(doc, i, dpi)
                processed = imaging.process_page(hi, angle, ecrop, color, palette,
                                                 removals, rot, persp,
                                                 ps.get("fixes"))
                if ps.get("overlays"):
                    processed = imaging.paste_overlays(
                        processed, ps["overlays"], ecrop, palette,
                        _render_overlay_src)
                if ps.get("shapes"):
                    processed = imaging.draw_shapes(processed, ps["shapes"], ecrop)
                wov = ps.get("wmo") or {}

                def _wp(key, default):
                    try:
                        return float(wov[key])
                    except (KeyError, TypeError, ValueError):
                        return default

                if wov:
                    stamp = bool(wov.get("on"))
                else:
                    stamp = watermark and (wm_scope != "page" or ps.get("wm"))
                if stamp:
                    sheet, centre = imaging.watermark_geometry(
                        processed.size, ecrop, wm_center_margins, cropped=True,
                        margin_crop=crop)
                    processed = imaging.apply_watermark(
                        processed,
                        _wp("opacity", wm_opacity), _wp("scale", wm_scale),
                        _wp("rotate", wm_rotate), _wp("dx", wm_dx),
                        _wp("dy", wm_dy), sheet, centre,
                        align_ink=wm_center_margins)
                if bd_on:
                    tpl = borders.load_template(btpls[tpl_i % len(btpls)])
                    tpl_i += 1
                    # per-page fit (falls back to the job-level values)
                    pbf = ps.get("bfit") or {}
                    pmode = str(pbf.get("mode") or bfit_mode)
                    if pmode not in ("page", "width", "fill"):
                        pmode = "page"
                    processed = borders.compose_bordered(
                        processed, tpl, bcfg, bheader,
                        zoom=borders._clampf(pbf.get("zoom", bzoom)),
                        stretch_w=borders._clampf(pbf.get("stretchW", bstretch_w)),
                        stretch_h=borders._clampf(pbf.get("stretchH", bstretch_h)),
                        fit_mode=pmode,
                        align_x=borders._clampa(pbf.get("ox", 0)),
                        align_y=borders._clampa(pbf.get("oy", 0)))
                images.append(processed.convert("RGB"))
            doc.close()

            if not images:
                continue              # every page of this PDF was deleted
            out_images.extend(images)

    for d in src_docs.values():
        d.close()

    if not out_images:
        return jsonify({"error": "every page is deleted — nothing to export"}), 400

    orig_name = job["files"][0]["name"]

    # "All boards": the notes are done — write them once per board, each with
    # that board's cover in front, and hand back the zip.
    if bd_on and bcovers:
        return _send_board_zip(out_images, bcovers, bcfg, dpi, orig_name,
                               bnumber, bname, bmedium, bsubject)

    # The cover belongs at the very front of the one document, not per file.
    if bd_on and bcover is not None:
        out_images.insert(0, borders.load_cover(
            bcover, bcfg["template_size"]).convert("RGB"))

    out_name = _export_name(orig_name, bd_on, bnumber, bname,
                            bboard, bmedium, bsubject)
    buf = io.BytesIO()
    out_images[0].save(buf, "PDF", resolution=float(dpi),
                       save_all=True, append_images=out_images[1:])
    buf.seek(0)
    return send_file(buf, mimetype="application/pdf",
                     as_attachment=True, download_name=out_name)


