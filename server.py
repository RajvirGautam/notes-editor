def _log_exception(context: str):
    try:
        with open(LOG_PATH, "a", encoding="utf-8") as fh:
            fh.write(f"\n[{datetime.now():%Y-%m-%d %H:%M:%S}] {context}\n")
            fh.write(traceback.format_exc())
    except OSError:
        pass


@app.errorhandler(Exception)
def _api_error(e):
    """
    Every error leaves this server as JSON {"error": ...}. The editor shows
    that text in a toast; without this, an unhandled exception became a plain
    HTML 500 page the client could only render as a blank "export failed".
    """
    if isinstance(e, HTTPException):        # abort(...) keeps its status/text
        return jsonify({"error": e.description}), e.code
    _log_exception(f"{request.method} {request.path}")
    if isinstance(e, MemoryError):
        return jsonify({"error": "the computer ran out of memory during this "
                        "step — close other apps, or export at a lower DPI "
                        "(150 or 200) and try again"}), 500
    return jsonify({"error": f"{type(e).__name__}: {e} — full details were "
                    "saved to notes-editor.log (next to server.py)"}), 500

# job_id -> {"files": [ {fid, name, path, pages: [ {angle, crop, w, h} ] } ] }
JOBS: dict = {}
# (job_id, fid, page) -> deskew-DPI base raster (PIL RGB), before any rotation
BASE_CACHE: dict = {}

# Analysing a page (render + skew detect + margin scan) takes a moment, so a
# 40-page upload is a long silent wait. Requests that do it publish a live
# page counter here under a token the client makes up and sends along; the
# client polls /api/progress with that token and draws a real bar.
# token -> {done, total, label, ts}
PROGRESS: dict = {}
PROGRESS_TTL = 600.0        # forget tokens whose request died without cleanup


@contextlib.contextmanager
def _progress(token: str, total: int = 0, label: str = ""):
    """
    Publish page progress for one request under `token`, and always forget it
    when the request ends. Yields the dict to tick (None if the client sent no
    token, which every progress-aware helper treats as "don't report").
    """
    if not token:
        yield None
        return
    cutoff = time.time() - PROGRESS_TTL
    for stale in [t for t, p in PROGRESS.items() if p["ts"] < cutoff]:
        PROGRESS.pop(stale, None)
    prog = {"done": 0, "total": int(total), "label": label, "ts": time.time()}
    PROGRESS[token] = prog
    try:
        yield prog
    finally:
        PROGRESS.pop(token, None)


@app.route("/api/progress")
def progress():
    """
    Progress of a long request, by the token the client sent with it. An
    unknown token is a normal answer rather than an error — the request may
    not have reached the server yet, or may already be finishing up.
    """
    prog = PROGRESS.get((request.args.get("token") or "").strip())
    if prog is None:
        return jsonify({"unknown": True})
    return jsonify({"done": prog["done"], "total": prog["total"],
                    "label": prog["label"]})


def _page_count(path: str) -> int:
    with contextlib.closing(fitz.open(path)) as doc:
        return doc.page_count


def _job(job_id: str) -> dict:
    job = JOBS.get(job_id)
    if not job:
        # Restarting the app empties JOBS, but an already-open browser tab
        # still shows the pages it loaded earlier — tell them what happened.
        abort(410, "the app was restarted since these pages were loaded, so "
                   "this session is gone — reload the browser tab and add "
                   "the PDFs again")
    return job


def _find_file(job: dict, fid: str) -> dict:
    for f in job["files"]:
        if f["fid"] == fid:
            return f
    abort(404, "unknown file")


