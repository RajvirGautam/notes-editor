def _analyse_pages(job_id: str, fid: str, path: str, start: int = 0,
                   prog: dict | None = None, label: str = "") -> list:
    """
    Auto-deskew + auto-margin pages [start:] of a working PDF and cache their
    base rasters. Returns the per-page dicts the editor works with.

    `prog` (from _progress) is ticked once per finished page, so a caller
    polling /api/progress sees the count climb through this loop.
    """
    doc = fitz.open(path)
    if prog is not None and label:
        prog["label"] = label
    pages = []
    for i in range(start, doc.page_count):
        base = imaging.render_page(doc, i, PREVIEW_DPI)
        angle = imaging.detect_skew(base)
        deskewed = imaging.deskew_image(base, angle)
        crop = imaging.content_bbox_fractions(deskewed)
        BASE_CACHE[(job_id, fid, i)] = base
        pages.append({
            "angle": angle,
            "crop": crop,
            "removals": [],
            "w": deskewed.width,
            "h": deskewed.height,
        })
        if prog is not None:
            prog["done"] += 1
            prog["ts"] = time.time()
    doc.close()
    return pages


def _append_uploads(job_id: str, f: dict, uploads: list,
                    prog: dict | None = None):
    """
    Merge uploaded PDFs onto the END of one working PDF, then analyse just the
    pages that appeared. The pages become part of that same document — they
    export inside the original PDF instead of as a separate file — and are
    editable like any other page.
    """
    doc = fitz.open(f["path"])
    start = doc.page_count
    names = []
    for up in uploads:
        blob = up.read()
        try:
            src = fitz.open(stream=blob, filetype="pdf")
        except Exception:
            doc.close()
            return jsonify({"error": f"{up.filename} is not a readable PDF"}), 400
        doc.insert_pdf(src)
        src.close()
        names.append(up.filename)
    added = doc.page_count - start
    tmp = f["path"] + ".tmp"
    doc.save(tmp)
    doc.close()
    os.replace(tmp, f["path"])

    if prog is not None:
        prog["total"] = added
    new_pages = _analyse_pages(job_id, f["fid"], f["path"], start,
                               prog=prog, label=f["name"])
    f["pages"].extend(new_pages)
    f["npages"] = len(f["pages"])
    return jsonify({"job": job_id, "appended": True, "fid": f["fid"],
                    "start": start, "npages": f["npages"],
                    "pages": new_pages, "sources": names})


@app.route("/api/upload", methods=["POST"])
def upload():
    uploads = [up for up in request.files.getlist("files")
               if (up.filename or "").lower().endswith(".pdf")]
    if not uploads:
        return jsonify({"error": "no PDF files"}), 400

    # "+ Add PDFs" sends the open job and the PDF being viewed: the new pages
    # are then merged onto the end of THAT document, so they stay one PDF and
    # still export as one file (not a zip of separate PDFs). An unknown or
    # expired job falls back to a fresh job — the client is told which
    # happened via "appended".
    job_id = (request.form.get("job") or "").strip()
    fid = (request.form.get("fid") or "").strip()
    token = (request.form.get("ptoken") or "").strip()

    with _progress(token, 0, f"Reading {len(uploads)} PDF(s)…") as prog:
        job = JOBS.get(job_id)
        if job and fid:
            target = next((f for f in job["files"] if f["fid"] == fid), None)
            if target is not None:
                return _append_uploads(job_id, target, uploads, prog)
        return _new_job(uploads, prog)


def _new_job(uploads: list, prog: dict | None = None):
    """
    Start a fresh job from uploaded PDFs. Every page count is read before any
    analysis, so a client polling progress gets a real denominator on its very
    first tick instead of watching the total grow file by file.
    """
    job_id = uuid.uuid4().hex[:12]
    job_dir = os.path.join(WORK_DIR, job_id)
    os.makedirs(job_dir, exist_ok=True)

    stored = []
    for up in uploads:
        fid = uuid.uuid4().hex[:8]
        path = os.path.join(job_dir, f"{fid}.pdf")
        up.save(path)
        try:
            npages = _page_count(path)
        except Exception:
            return jsonify({"error": f"{up.filename} is not a readable PDF"}), 400
        stored.append({"fid": fid, "name": up.filename, "path": path,
                       "npages": npages})

    if prog is not None:
        prog["total"] = sum(s["npages"] for s in stored)

    files = []
    for s in stored:
        pages = _analyse_pages(job_id, s["fid"], s["path"],
                               prog=prog, label=s["name"])
        files.append({**s, "npages": len(pages), "pages": pages})

    if not files:
        return jsonify({"error": "no valid PDFs"}), 400

    JOBS[job_id] = {"files": files, "dir": job_dir}

    # Strip server-only fields from the response.
    payload_files = [{
        "fid": f["fid"], "name": f["name"], "npages": f["npages"],
        "pages": f["pages"],
    } for f in files]
    return jsonify({"job": job_id, "files": payload_files, "appended": False})


def _color_from_args(args) -> dict:
    """Build a colour dict from flat query params (c* prefixed)."""
    return {
        "mode": args.get("cmode", "none"),
        "brightness": float(args.get("cbright", "1")),
        "contrast": float(args.get("ccontrast", "1")),
        "saturation": float(args.get("csat", "1")),
        "whiten": float(args.get("cwhiten", "0")),
        "deyellow": float(args.get("cdeyellow", "0")),
    }


def _crop_from_args(args):
    """Optional crop insets from query params (cr*); None if no crop."""
    c = {
        "left": float(args.get("crl", "0") or 0),
        "top": float(args.get("crt", "0") or 0),
        "right": float(args.get("crr", "0") or 0),
        "bottom": float(args.get("crb", "0") or 0),
    }
    return None if all(v <= 0 for v in c.values()) else c


def _persp_from_args(args):
    """
    Four-corner perspective quad from the compact query param (psp).

    Sent as eight comma-separated fractions — tl, tr, br, bl — because it rides
    on every preview and thumbnail URL. None means "leave the page flat".
    """
    raw = args.get("psp", "")
    if not raw:
        return None
    try:
        nums = [float(v) for v in raw.split(",")]
    except ValueError:
        return None
    return nums if len(nums) == 8 else None


def _overlays_from_args(args) -> list[dict]:
    """Parse merged-page overlays from query param (ov, JSON list)."""
    raw = args.get("ov", "")
    if not raw:
        return []
    try:
        data = json.loads(raw)
        return data if isinstance(data, list) else []
    except ValueError:
        return []


def _shapes_from_args(args) -> list[dict]:
    """Parse shape-filler polygons from query param (shp, JSON list)."""
    raw = args.get("shp", "")
    if not raw:
        return []
    try:
        data = json.loads(raw)
        return data if isinstance(data, list) else []
    except ValueError:
        return []


def _removals_from_args(args) -> list[dict]:
    """Parse removals from query param (rms)."""
    raw = args.get("rms", "")
    if not raw:
        return []
    import json
    try:
        if raw.startswith("["):
            return json.loads(raw)
        res = []
        for pair in raw.split("|"):
            parts = pair.split(",")
            if len(parts) == 2:
                res.append({"top": float(parts[0]), "bottom": float(parts[1])})
        return res
    except Exception:
        return []


def _fixes_from_args(args) -> list[dict]:
    """Parse spelling fixes from query param (fxs, JSON list of {id, rect})."""
    raw = args.get("fxs", "")
    if not raw:
        return []
    try:
        data = json.loads(raw)
        return data if isinstance(data, list) else []
    except ValueError:
        return []


@app.route("/api/preview")
def preview():
    """
    Deskewed (+ optional crop / removals / scan / colour) preview PNG for one page.
    Pass maxdim to get a small thumbnail (crop is applied when maxdim is set).
    """
    job_id = request.args.get("job", "")
    fid = request.args.get("fid", "")
    page = int(request.args.get("page", "0"))
    angle = float(request.args.get("angle", "0"))
    rot = float(request.args.get("rot", "0") or 0)
    maxdim = int(request.args.get("maxdim", "0"))
    color = _color_from_args(request.args)
    crop = _crop_from_args(request.args)
    removals = _removals_from_args(request.args)
    watermark = request.args.get("wm", "0") == "1"
    wm_opacity = float(request.args.get("wmop", "1") or 1)
    wm_scale = float(request.args.get("wmscale", "1") or 1)
    wm_rotate = float(request.args.get("wmrot", "0") or 0)
    wm_dx = float(request.args.get("wmdx", "0") or 0)
    wm_dy = float(request.args.get("wmdy", "0") or 0)
    # Where the watermark anchors: the margin box or the whole sheet. The page's
    # crop insets come in separately (w*) because the main preview shows the
    # *uncropped* page — it needs the margins for placement without cropping.
    wm_center_margins = request.args.get("wmcm", "0") == "1"
    wm_crop = {
        "left": float(request.args.get("wcl", "0") or 0),
        "top": float(request.args.get("wct", "0") or 0),
        "right": float(request.args.get("wcr", "0") or 0),
        "bottom": float(request.args.get("wcb", "0") or 0),
    }

    _job(job_id)
    base = BASE_CACHE.get((job_id, fid, page))
    if base is None:
        abort(404, "no cached page")

    # For thumbnails, downscale the source first so all pages render fast.
    src = base
    if 0 < maxdim < max(base.size):
        scale = maxdim / max(base.size)
        src = base.resize((max(1, int(base.width * scale)),
                           max(1, int(base.height * scale))), Image.BILINEAR)

    palette = _job(job_id).get("palette")
    out = imaging.deskew_image(imaging.rotate_page(src, rot), angle)
    # The perspective warp joins rotate/deskew as a geometry fix, before
    # anything measures the page. It keeps the sheet's size, so the crop guides
    # and gap bands drawn over this preview still mean what they did.
    out = imaging.apply_perspective(out, _persp_from_args(request.args))
    # Removals before crop: their fractions are in uncropped-deskewed space.
    if removals:
        out = imaging.apply_removals(out, removals)
    # Spelling fixes live in that same post-removals space, and go on before
    # the crop and colour so the mended ink is graded with the page.
    fixes = _fixes_from_args(request.args)
    if fixes:
        out = imaging.apply_fixes(out, fixes)
    # Content pulled from other pages is part of the page too: where it sits
    # past the margins the sheet grows to keep it instead of clipping it, so
    # every step from here on works against that grown box.
    overlays = _overlays_from_args(request.args)
    ecrop = imaging.expanded_crop(crop, overlays)
    if ecrop:
        out = imaging.apply_crop(out, ecrop)
    out = imaging.finish_color(out, color, palette)
    # Merged-page overlays sit under the watermark, exactly like on export.
    if overlays:
        out = imaging.paste_overlays(
            out, overlays, ecrop, palette,
            lambda ov: BASE_CACHE.get(
                (job_id, str(ov.get("fid", "")), int(ov.get("page", 0) or 0))))
    # Shape-filler polygons cover content under the watermark, like on export.
    shapes = _shapes_from_args(request.args)
    if shapes:
        out = imaging.draw_shapes(out, shapes, ecrop)
    if watermark:
        sheet, centre = imaging.watermark_geometry(
            out.size, ecrop if ecrop else wm_crop, wm_center_margins,
            cropped=ecrop is not None, margin_crop=wm_crop)
        out = imaging.apply_watermark(out, wm_opacity, wm_scale, wm_rotate,
                                      wm_dx, wm_dy, sheet, centre,
                                      align_ink=wm_center_margins)
    return Response(imaging.to_png_bytes(out), mimetype="image/png")


@app.route("/api/fix/generate", methods=["POST"])
def fix_generate():
    """
    Rewrite one misspelled word in the writer's own hand (via OpenAI).

    Body: { job, fid, page, rect: [x0,y0,x1,y1], correct, wrong?, n?,
            angle?, rotate?, persp?, removals? }
    `rect` is in fractions of the uncropped deskewed post-removals page —
    exactly what the user boxed on the main preview. The page is re-rendered
    at export DPI (300) so the word reaches the API at full detail, whatever
    the on-screen preview resolution.

    Returns { candidates: [ {id, rect, png, thumb} ] } — the client shows the
    thumbs, and the one the user picks is stored on the page as
    {id, rect, png} (the png rides along so drafts and exports survive a
    server restart).
    """
    data = request.get_json(force=True)
    job = _job(data.get("job", ""))
    f = _find_file(job, data.get("fid", ""))
    page = int(data.get("page", 0))
    rect = data.get("rect") or []
    correct = str(data.get("correct", "") or "").strip()
    wrong = str(data.get("wrong", "") or "").strip()
    n = int(data.get("n", 3) or 3)
    if len(rect) != 4:
        return jsonify({"error": "bad word box"}), 400
    if not correct:
        return jsonify({"error": "type the correct spelling first"}), 400
    if not spellfix.api_ready():
        return jsonify({"error": "OPENAI_API_KEY missing — put it in a .env "
                        "file next to server.py and restart"}), 400
    if not 0 <= page < _page_count(f["path"]):
        return jsonify({"error": "bad page"}), 400

    # Same geometry chain as export, at export DPI, stopping right where the
    # fix will later be composited (post-removals, pre-crop, raw colour).
    with contextlib.closing(fitz.open(f["path"])) as doc:
        hi = imaging.render_page(doc, page, DEFAULT_EXPORT_DPI)
    geo = imaging.apply_perspective(
        imaging.deskew_image(
            imaging.rotate_page(hi, float(data.get("rotate", 0) or 0)),
            float(data.get("angle", 0) or 0)),
        data.get("persp"))
    geo = imaging.apply_removals(geo, data.get("removals") or [])

    try:
        cands = spellfix.generate_candidates(geo, [float(v) for v in rect],
                                             wrong, correct, n)
    except (RuntimeError, ValueError) as e:
        return jsonify({"error": str(e)}), 502

    import base64
    out = []
    for c in cands:
        PATCHES[c["id"]] = Image.open(io.BytesIO(c["png"])).convert("RGBA")
        out.append({"id": c["id"], "rect": c["rect"],
                    "png": base64.b64encode(c["png"]).decode(),
                    "thumb": base64.b64encode(c["thumb"]).decode()})
    return jsonify({"candidates": out})


@app.route("/api/spellcheck", methods=["POST"])
def spellcheck():
    """
    Read pages with a vision model and list suspected spelling mistakes.

    Body: { job, ptoken?, pages: [ {fid, pi, src, angle?, rotate?, persp?,
            removals?} ] } — one entry per page to check, with that page's
    geometry so the returned x/y positions line up with the editor preview.
    Returns { findings: [ {fid, pi, wrong, correct, context, x, y} ],
              errors: [ {pi, error} ] }. Text only — no image generation.
    """
    data = request.get_json(force=True)
    job_id = data.get("job", "")
    job = _job(job_id)
    pages = [p for p in (data.get("pages") or []) if isinstance(p, dict)]
    if not pages:
        return jsonify({"error": "no pages to check"}), 400
    if not spellfix.api_ready():
        return jsonify({"error": "OPENAI_API_KEY missing — put it in a .env "
                        "file next to server.py and restart"}), 400

    def page_image(ps):
        fid = str(ps.get("fid", ""))
        src = int(ps.get("src", 0) or 0)
        base = BASE_CACHE.get((job_id, fid, src))
        if base is None:
            f = _find_file(job, fid)
            with contextlib.closing(fitz.open(f["path"])) as doc:
                base = imaging.render_page(doc, src, PREVIEW_DPI)
        # Same space as the main preview (uncropped, post-removals), so the
        # model's word positions can be marked straight onto it.
        geo = imaging.apply_perspective(
            imaging.deskew_image(
                imaging.rotate_page(base, float(ps.get("rotate", 0) or 0)),
                float(ps.get("angle", 0) or 0)),
            ps.get("persp"))
        geo = imaging.apply_removals(geo, ps.get("removals") or [])
        # Apply existing spelling fixes, so mended words don't get re-flagged.
        return imaging.apply_fixes(geo, ps.get("fixes") or [])

    token = (data.get("ptoken") or "").strip()
    findings, errors = [], []
    with _progress(token, len(pages), "Reading handwriting…") as prog:
        from concurrent.futures import ThreadPoolExecutor

        def work(ps):
            try:
                ms = spellfix.check_page(page_image(ps))
                return [{**m, "fid": str(ps.get("fid", "")),
                         "pi": int(ps.get("pi", 0) or 0)} for m in ms]
            except Exception as e:
                return {"pi": int(ps.get("pi", 0) or 0), "error": str(e)}

        with ThreadPoolExecutor(max_workers=4) as ex:
            for res in ex.map(work, pages):
                if prog is not None:
                    prog["done"] += 1
                if isinstance(res, dict):
                    errors.append(res)
                else:
                    findings.extend(res)
    findings.sort(key=lambda m: (m["fid"], m["pi"], m["y"]))
    return jsonify({"findings": findings, "errors": errors})


@app.route("/api/detect_gaps", methods=["POST", "GET"])
def detect_gaps():
    """Auto-detect blank vertical gaps for a given page."""
    req_json = request.get_json(silent=True) or {}
    job_id = (request.args.get("job") or "") or req_json.get("job", "")
    fid = (request.args.get("fid") or "") or req_json.get("fid", "")
    _page = request.args.get("page")
    page = int(_page) if _page is not None else int(req_json.get("page", 0))
    _angle = request.args.get("angle")
    angle = float(_angle) if _angle is not None else float(req_json.get("angle", 0))
    _rot = request.args.get("rot")
    rot = float(_rot) if _rot is not None else float(req_json.get("rotate", 0) or 0)
    crop = _crop_from_args(request.args) if request.args.get("crl") else req_json.get("crop")
    persp = _persp_from_args(request.args) if request.args.get("psp") \
        else req_json.get("persp")

    _job(job_id)
    base = BASE_CACHE.get((job_id, fid, page))
    if base is None:
        abort(404, "no cached page")

    deskewed = imaging.apply_perspective(
        imaging.deskew_image(imaging.rotate_page(base, rot), angle), persp)
    if crop:
        deskewed = imaging.apply_crop(deskewed, crop)

    gaps = imaging.auto_detect_blank_gaps(deskewed)
    if crop:
        # Detection ran on the cropped page (better signal — skips the header
        # and margins), but gap fractions are stored in uncropped-deskewed
        # space, so map them back through the crop insets.
        ct = float(crop.get("top", 0) or 0)
        cb = float(crop.get("bottom", 0) or 0)
        kh = max(1e-6, 1.0 - ct - cb)
        gaps = [{"top": round(ct + g["top"] * kh, 4),
                 "bottom": round(ct + g["bottom"] * kh, 4)} for g in gaps]
    return jsonify({"gaps": gaps})


